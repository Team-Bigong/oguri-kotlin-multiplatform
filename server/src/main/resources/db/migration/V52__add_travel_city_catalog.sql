CREATE TABLE cities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (name = btrim(name) AND name <> ''),
    country_code CHAR(2) NOT NULL CHECK (country_code ~ '^[A-Z]{2}$'),
    region_label TEXT NOT NULL CHECK (region_label = btrim(region_label) AND region_label <> ''),
    time_zone TEXT NOT NULL CHECK (btrim(time_zone) <> ''),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    population BIGINT NOT NULL DEFAULT 0 CHECK (population >= 0),
    CHECK (char_length(name || ' · ' || region_label) <= 100)
);

CREATE UNIQUE INDEX cities_qualified_label ON cities ((name || ' · ' || region_label));
CREATE INDEX cities_name_prefix ON cities (lower(name) text_pattern_ops);

CREATE TABLE city_aliases (
    city_id BIGINT NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (name = btrim(name) AND name <> ''),
    PRIMARY KEY (city_id, name)
);

CREATE INDEX city_aliases_name_prefix ON city_aliases (lower(name) text_pattern_ops);

ALTER TABLE travel_plan_cities ADD COLUMN city_id BIGINT REFERENCES cities(id);
